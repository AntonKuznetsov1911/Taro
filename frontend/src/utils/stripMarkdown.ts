/**
 * Удаление markdown-разметки из текста.
 *
 * Генераторы текстов (src/utils/offlineApi.ts и экранные генераторы) отдают
 * markdown: `**жирный**`, `*курсив*`, заголовки `#`/`##`/`###`,
 * горизонтальные линии `---`, списки `- `. Полноценные экраны рендерят это
 * через <MarkdownRenderer />, но там, где нужна именно строка (превью в карточке,
 * подзаголовок, однострочная сводка, текст для «Поделиться»), разметку нужно
 * убрать — иначе пользователь видит служебные символы.
 */
export function stripMarkdown(text?: string | null): string {
  if (typeof text !== 'string' || text.length === 0) {
    return '';
  }

  return (
    text
      // Горизонтальные линии: ---, ***, ___ (на отдельной строке)
      .replace(/^[ \t]*([-*_])[ \t]*(?:\1[ \t]*){2,}$/gm, '')
      // Блоки кода ```lang ... ```
      .replace(/^[ \t]*```.*$/gm, '')
      // Заголовки # / ## / ### ...
      .replace(/^[ \t]*#{1,6}[ \t]*/gm, '')
      // Цитаты
      .replace(/^[ \t]*>[ \t]?/gm, '')
      // Маркеры списков - / * / + → типографская точка
      .replace(/^[ \t]*[-*+][ \t]+/gm, '• ')
      // Ссылки [текст](url) и изображения ![alt](url)
      .replace(/!?\[([^\]]*)\]\([^)]*\)/g, '$1')
      // **жирный** / __жирный__
      .replace(/\*\*([^*]+)\*\*/g, '$1')
      .replace(/__([^_]+)__/g, '$1')
      // *курсив* / _курсив_
      .replace(/\*([^*\n]+)\*/g, '$1')
      .replace(/(^|[\s(])_([^_\n]+)_(?=[\s).,!?:;]|$)/g, '$1$2')
      // `код`
      .replace(/`([^`]*)`/g, '$1')
      // Одиночные остатки разметки (непарные * и #)
      .replace(/[*#]/g, '')
      // Хвостовые пробелы и лишние пустые строки
      .replace(/[ \t]+$/gm, '')
      .replace(/\n{3,}/g, '\n\n')
      .trim()
  );
}

/**
 * Однострочное превью: разметка убрана, переводы строк схлопнуты в пробелы.
 * Удобно для карточек истории и коротких подписей.
 */
export function toPlainPreview(text?: string | null, maxLength?: number): string {
  const plain = stripMarkdown(text).replace(/\s*\n+\s*/g, ' ').replace(/[ \t]{2,}/g, ' ').trim();

  if (typeof maxLength === 'number' && maxLength > 0 && plain.length > maxLength) {
    return `${plain.slice(0, maxLength).trimEnd()}…`;
  }

  return plain;
}
